import { ScenarioType } from './types.js';
import type { TicketData } from './types.js';

export class CommentBuilder {
  buildPlanComment(
    jiraNumber: string,
    scenarioType: ScenarioType,
    filename: string,
    tickets: TicketData[]
  ): string {
    const ticketList = tickets.map((t, i) =>
      `${i + 1}. **${t.summary}** _(${t.sourceRef})_`
    ).join('\n');

    return `## BCAT Plan Preview for ${jiraNumber}

**Scenario Type:** ${scenarioType}
**Source File:** ${filename}
**Tickets to Create:** ${tickets.length}

---

### Planned Tickets

${ticketList}

---

**Next Steps:**
1. Review the ticket list above
2. Assign approvers to this ticket (required for execution)
3. Once approved, BCAT-EXECUTOR will create all ${tickets.length} JIRA tickets automatically

_Generated by BCAT-PLANNER on ${new Date().toISOString()}_`;
  }

  buildCompletionComment(
    jiraNumber: string,
    scenarioType: ScenarioType,
    filename: string,
    created: Array<{ jiraKey: string; summary: string; sourceRef: string }>,
    failed: Array<{ summary: string; sourceRef: string; error: string }> = []
  ): string {
    const total = created.length + failed.length;
    const ticketList = created.map((t, i) =>
      `${i + 1}. [${t.jiraKey}] **${t.summary}**`
    ).join('\n');

    const failedSection = failed.length > 0
      ? `\n---\n\n### Failed Tickets (${failed.length}/${total})\n\n` +
        failed.map((t, i) =>
          `${i + 1}. **${t.summary}** _(${t.sourceRef})_\n   - Error: \`${t.error}\``
        ).join('\n') + '\n'
      : '';

    const status = failed.length === 0
      ? 'Complete'
      : failed.length === total
        ? 'Failed'
        : 'Partial';

    return `## BCAT Execution ${status} for ${jiraNumber}

**Scenario Type:** ${scenarioType}
**Source File:** ${filename}
**Tickets Created:** ${created.length}/${total}${failed.length > 0 ? ` — ⚠️ ${failed.length} failed` : ''}

---

### Created Tickets (${created.length})

${created.length > 0 ? ticketList : '_None_'}
${failedSection}
---

${created.length > 0 ? `All created tickets have been:
- Linked to parent ticket ${jiraNumber}
- Attached with per-ticket Excel data (where applicable)` : ''}

_Generated by BCAT-EXECUTOR on ${new Date().toISOString()}_`;
  }

  buildErrorComment(
    jiraNumber: string,
    phase: 'PLANNING' | 'EXECUTION',
    error: string
  ): string {
    return `## BCAT ${phase} Error for ${jiraNumber}

**Status:** Failed
**Phase:** ${phase}

---

### Error Details

\`\`\`
${error}
\`\`\`

---

Please review the error above and re-trigger after correcting the issue.

_Generated by BCAT-${phase === 'PLANNING' ? 'PLANNER' : 'EXECUTOR'} on ${new Date().toISOString()}_`;
  }
}
