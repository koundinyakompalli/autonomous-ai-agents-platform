/**
 * BEACON Worker
 * Processes JIRA tickets labeled with "BEACON"
 * 
 * Workflow:
 * 1. Poll for BEACON labeled tickets
 * 2. Download XLSX attachment from JIRA
 * 3. Send XLSX to MOANA API for SQL generation
 * 4. Create BEACONAgent to validate SQL against HBM models
 * 5. Post results to JIRA
 */

import { AgentWorker, type ProcessResult } from '../AgentWorker.js';
import { BEACONAgent, type BEACONValidationResult } from '../../agents/beacon/index.js';
import { createLogger } from '../../utils/logger.js';
import { bufferToBlobPart } from '../../utils/blob.js';
import type { EventEmitter } from 'events';

const logger = createLogger('beacon-worker');
import * as fs from 'fs';
import * as path from 'path';
import * as os from 'os';

// MOANA API Configuration
const MOANA_BASE_URL = process.env.MOANA_BASE_URL || 'https://moana.mhkdevsandbox.com/api';
const MOANA_USER_ID = process.env.MOANA_USER_ID || 'beacon@specter.mhk.com';

/**
 * MOANA API response for file upload
 */
interface MoanaUploadResponse {
    success: boolean;
    message: string;
    data: {
        fileName: string;
        headers: string[];
        rowCount: number;
        preview: Record<string, any>[];
    };
}

/**
 * MOANA API response for SQL generation
 */
interface MoanaGenerateResponse {
    query_id: string;
    sql: string;
    explanation: string;
    detected_module: string;
    detected_keywords: string[];
    context_used: string[];
    metadata: {
        tokens_used: number;
        latency_ms: number;
        model: string;
    };
}

/**
 * BEACON Worker - Backend Execution Agent for Case Orchestrated Normalization
 */
export class BEACONWorker extends AgentWorker {
    private jiraBaseUrl: string;

    constructor(repositoryPath: string, enableStatusServer: boolean = false) {
        super({
            agentName: 'BEACON',
            repositoryPath,
            pollingIntervalMs: 10000, // 10 seconds
            batchSize: 1,
            enableStatusServer,
        });

        this.jiraBaseUrl = process.env.JIRA_BASE_URL || '';

        logger.info({
            repositoryPath,
            enableStatusServer,
            pollingIntervalMs: 10000,
            jiraBaseUrl: this.jiraBaseUrl,
            moanaBaseUrl: MOANA_BASE_URL
        }, '[BEACON_WORKER_INIT] BEACONWorker initialized');
    }

    /**
     * Process BEACON task - generate SQL via MOANA and validate
     */
    protected async process(
        jiraNumber: string,
        taskId: number,
        taskDescription: string,
        additionalContext: string,
        repositoryPath: string,
        eventEmitter?: EventEmitter
    ): Promise<ProcessResult> {
        const startTime = Date.now();

        const logContext = {
            jira: jiraNumber,
            taskId,
            repositoryPath,
            correlationId: `beacon-${taskId}-${jiraNumber}`,
        };

        logger.info(logContext, '[BEACON_PROCESS_START] Starting SQL generation from XLSX');

        let xlsxFilePath: string | null = null;

        try {
            // Step 1: Download XLSX attachment from JIRA
            logger.info(logContext, '[BEACON_DOWNLOAD] Downloading XLSX attachment from JIRA');
            xlsxFilePath = await this.downloadXlsxAttachment(jiraNumber, logContext);

            if (!xlsxFilePath) {
                throw new Error('No XLSX attachment found in JIRA ticket');
            }

            logger.info({
                ...logContext,
                xlsxPath: xlsxFilePath
            }, '[BEACON_DOWNLOAD_SUCCESS] XLSX file downloaded');

            // Step 2: Call MOANA API to generate SQL
            logger.info(logContext, '[BEACON_MOANA_START] Calling MOANA API for SQL generation');
            const moanaResult = await this.callMoanaAPI(xlsxFilePath, jiraNumber, additionalContext);

            logger.info({
                ...logContext,
                moanaQueryId: moanaResult.queryId,
                sqlLength: moanaResult.sql.length,
                rowCount: moanaResult.fileInfo.rowCount
            }, '[BEACON_MOANA_SUCCESS] SQL generated by MOANA');

            // Step 3: Create BEACON agent and validate SQL
            logger.info(logContext, '[BEACON_AGENT_CREATE] Creating BEACONAgent for validation');
            const agent = new BEACONAgent({
                repositoryPath,
                onProgress: (msg) => {
                    logger.debug({
                        ...logContext,
                        progressMessage: msg,
                    }, '[BEACON_PROGRESS] Agent progress update');
                },
                eventEmitter,
            });

            logger.info(logContext, '[BEACON_VALIDATE_START] Starting SQL validation');
            const validationResult = await agent.validate(
                moanaResult.sql,
                moanaResult.fileInfo,
                { queryId: moanaResult.queryId, explanation: moanaResult.explanation },
                jiraNumber
            );

            const durationMs = Date.now() - startTime;

            logger.info({
                ...logContext,
                durationMs,
                riskLevel: validationResult.riskLevel,
                decision: validationResult.decision,
                validationSuccess: validationResult.success
            }, '[BEACON_PROCESS_SUCCESS] SQL generation and validation complete');

            // Step 4: Format output
            const output = this.formatOutput(jiraNumber, moanaResult, validationResult);

            // Estimate cost
            const estimatedCost = this.estimateCost(validationResult);

            return {
                success: true,
                output,
                metrics: {
                    totalTokens: validationResult.metrics.tokensUsed || { input: 0, output: 0 },
                    iterations: validationResult.metrics.toolCalls,
                    cost: estimatedCost,
                    durationMs,
                },
            };

        } catch (error: any) {
            const durationMs = Date.now() - startTime;

            logger.error({
                ...logContext,
                durationMs,
                errorName: error.name,
                errorMessage: error.message,
                errorStack: error.stack,
            }, '[BEACON_PROCESS_ERROR] Error during SQL generation');

            return {
                success: false,
                output: '',
                error: error.message,
                metrics: {
                    durationMs,
                },
            };
        } finally {
            // Cleanup temp file
            if (xlsxFilePath) {
                try {
                    fs.unlinkSync(xlsxFilePath);
                    logger.debug(logContext, '[BEACON_CLEANUP] Temporary XLSX file deleted');
                } catch (cleanupError) {
                    logger.warn({
                        ...logContext,
                        error: cleanupError
                    }, '[BEACON_CLEANUP_WARN] Failed to delete temporary file');
                }
            }
        }
    }

    /**
     * Download XLSX attachment from JIRA ticket
     */
    private async downloadXlsxAttachment(
        jiraNumber: string,
        logContext: Record<string, any>
    ): Promise<string | null> {
        try {
            // Fetch issue to get attachments
            const issueUrl = `${this.jiraBaseUrl}/rest/api/3/issue/${jiraNumber}?fields=attachment`;

            const basicAuth = `Basic ${Buffer.from(`${this.agentJiraUsername}:${this.agentJiraToken}`).toString('base64')}`;
            const response = await fetch(issueUrl, {
                headers: {
                    'Authorization': basicAuth,
                    'Accept': 'application/json'
                }
            });

            if (!response.ok) {
                throw new Error(`JIRA API error: ${response.status} ${response.statusText}`);
            }

            const data = await response.json() as any;
            const attachments = data.fields?.attachment || [];

            logger.debug({
                ...logContext,
                attachmentCount: attachments.length
            }, '[BEACON_ATTACHMENTS] Found attachments');

            // Find XLSX file
            const xlsxAttachment = attachments.find((att: any) => {
                const filename = (att.filename || '').toLowerCase();
                return filename.endsWith('.xlsx') || filename.endsWith('.xls');
            });

            if (!xlsxAttachment) {
                logger.warn(logContext, '[BEACON_NO_XLSX] No XLSX attachment found');
                return null;
            }

            logger.info({
                ...logContext,
                filename: xlsxAttachment.filename,
                size: xlsxAttachment.size
            }, '[BEACON_DOWNLOAD_START] Downloading XLSX file');

            // Download file to temp directory
            const tempDir = os.tmpdir();
            const tempFilePath = path.join(tempDir, `beacon-${jiraNumber}-${Date.now()}.xlsx`);

            const fileResponse = await fetch(xlsxAttachment.content, {
                headers: {
                    'Authorization': basicAuth
                }
            });

            if (!fileResponse.ok) {
                throw new Error(`File download failed: ${fileResponse.status} ${fileResponse.statusText}`);
            }

            const arrayBuffer = await fileResponse.arrayBuffer();
            fs.writeFileSync(tempFilePath, Buffer.from(arrayBuffer));

            logger.info({
                ...logContext,
                tempFilePath,
                fileSize: fs.statSync(tempFilePath).size
            }, '[BEACON_DOWNLOAD_COMPLETE] XLSX file saved to temp');

            return tempFilePath;

        } catch (error: any) {
            logger.error({
                ...logContext,
                error: error.message
            }, '[BEACON_DOWNLOAD_ERROR] Failed to download XLSX');
            throw error;
        }
    }

    /**
     * Call MOANA API to generate SQL from XLSX
     */
    private async callMoanaAPI(
        xlsxFilePath: string,
        jiraNumber: string,
        additionalContext?: string
    ): Promise<{
        sql: string;
        explanation: string;
        queryId: string;
        fileInfo: { fileName: string; rowCount: number; headers: string[] };
    }> {
        const sessionId = `beacon-${jiraNumber}-${Date.now()}`;

        // Step 1: Upload file to MOANA
        logger.info({ sessionId, filePath: xlsxFilePath }, '[BEACON_MOANA_UPLOAD] Uploading file to MOANA');

        // Create form data for file upload using native FormData
        const fileBuffer = fs.readFileSync(xlsxFilePath);
        const fileName = path.basename(xlsxFilePath);

        const formData = new FormData();
        formData.append('file', new Blob([bufferToBlobPart(fileBuffer)]), fileName);
        formData.append('sessionId', sessionId);

        const uploadResponse = await fetch(`${MOANA_BASE_URL}/query/upload-file`, {
            method: 'POST',
            body: formData
        });

        if (!uploadResponse.ok) {
            const errorText = await uploadResponse.text();
            throw new Error(`MOANA file upload failed: ${uploadResponse.status} - ${errorText}`);
        }

        const uploadData = await uploadResponse.json() as MoanaUploadResponse;

        if (!uploadData.success) {
            throw new Error(`MOANA file upload failed: ${uploadData.message}`);
        }

        const fileInfo = {
            fileName: uploadData.data.fileName,
            rowCount: uploadData.data.rowCount,
            headers: uploadData.data.headers
        };

        logger.info(fileInfo, '[BEACON_MOANA_UPLOAD_SUCCESS] File uploaded to MOANA');

        // Step 2: Generate SQL from uploaded file
        logger.info({ sessionId }, '[BEACON_MOANA_GENERATE] Requesting SQL generation from MOANA');

        const queryText = additionalContext
            ? `${additionalContext}\n\nGenerate UPDATE statements for all rows in the uploaded file. Wrap all statements in a transaction with START TRANSACTION and COMMIT.`
            : 'Generate UPDATE statements for all rows in the uploaded file to update the specified fields. Wrap all statements in a transaction with START TRANSACTION and COMMIT.';

        const generateResponse = await fetch(`${MOANA_BASE_URL}/query/generate`, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json'
            },
            body: JSON.stringify({
                query: queryText,
                userId: MOANA_USER_ID,
                sessionId: sessionId
            })
        });

        if (!generateResponse.ok) {
            const errorText = await generateResponse.text();
            throw new Error(`MOANA SQL generation failed: ${generateResponse.status} - ${errorText}`);
        }

        const generateData = await generateResponse.json() as MoanaGenerateResponse;

        logger.info({
            queryId: generateData.query_id,
            detectedModule: generateData.detected_module,
            tokensUsed: generateData.metadata.tokens_used
        }, '[BEACON_MOANA_GENERATE_SUCCESS] SQL generated by MOANA');

        return {
            sql: generateData.sql,
            explanation: generateData.explanation,
            queryId: generateData.query_id,
            fileInfo
        };
    }

    /**
     * Estimate cost for BEACON processing
     */
    private estimateCost(validationResult: BEACONValidationResult): number {
        if (validationResult.metrics.costUsd) {
            return validationResult.metrics.costUsd;
        }

        // Estimate based on tokens if available
        const tokens = validationResult.metrics.tokensUsed;
        if (tokens) {
            const inputCost = (tokens.input / 1000) * 0.003;
            const outputCost = (tokens.output / 1000) * 0.015;
            return inputCost + outputCost;
        }

        // Default estimate
        return 0.05;
    }

    /**
     * Format BEACON result as markdown for JIRA
     */
    private formatOutput(
        jiraNumber: string,
        moanaResult: { sql: string; explanation: string; queryId: string; fileInfo: { fileName: string; rowCount: number; headers: string[] } },
        validationResult: BEACONValidationResult
    ): string {
        const checklist = validationResult.validationChecklist;

        // Build checklist markdown
        let checklistMd = '';
        if (checklist && checklist.length > 0) {
            checklistMd = checklist.map(category => {
                const items = category.items.map(item => {
                    const icon = item.status === 'PASS' ? '✅' :
                        item.status === 'FAIL' ? '❌' :
                            item.status === 'WARNING' ? '⚠️' : '➖';
                    return `- [${item.status === 'PASS' ? 'x' : ' '}] ${item.check}: ${icon} ${item.status} — ${item.details}`;
                }).join('\n');
                return `### ${category.category}\n${items}`;
            }).join('\n\n');
        }

        // Risk/Decision styling
        const riskEmoji = validationResult.riskLevel === 'LOW' ? '🟢' :
            validationResult.riskLevel === 'MEDIUM' ? '🟡' : '🔴';
        const decisionEmoji = validationResult.decision === 'SAFE TO EXECUTE' ? '✅' :
            validationResult.decision === 'EXECUTE WITH CAUTION' ? '⚠️' :
                validationResult.decision === 'NEEDS REVIEW' ? '🔍' : '🚫';

        return `# BEACON SQL Generation for ${jiraNumber}

## Backend Execution Agent for Case Orchestrated Normalization

**Generated:** ${new Date().toISOString()}  
**Processing Time:** ${(validationResult.metrics.durationMs / 1000).toFixed(2)}s  
**Source File:** ${moanaResult.fileInfo.fileName}  
**Row Count:** ${moanaResult.fileInfo.rowCount}

---

## 📊 File Information

**Headers:** ${moanaResult.fileInfo.headers.join(', ')}  
**Total Rows:** ${moanaResult.fileInfo.rowCount}

---

## 🔧 Generated SQL

**MOANA Query ID:** \`${moanaResult.queryId}\`

\`\`\`sql
${moanaResult.sql}
\`\`\`

### MOANA Explanation
${moanaResult.explanation}

---

## ✅ Validation Checklist

${checklistMd || '_(No validation checklist available)_'}

---

## 🔍 Validated Against

**Repository:** ${validationResult.validatedAgainst.repository}  
**HBM Models:** ${validationResult.validatedAgainst.models.length > 0 ? validationResult.validatedAgainst.models.join(', ') : '_(None checked)_'}  
**Tables Found:** ${validationResult.validatedAgainst.tablesFound.length > 0 ? validationResult.validatedAgainst.tablesFound.join(', ') : '_(None)_'}  
**Columns Validated:** ${validationResult.validatedAgainst.columnsValidated.length > 0 ? validationResult.validatedAgainst.columnsValidated.length : 0}

---

## 🎯 Risk Assessment

**Risk Level:** ${riskEmoji} **${validationResult.riskLevel}**  
**Decision:** ${decisionEmoji} **${validationResult.decision}**

### Recommendations

${validationResult.recommendations && validationResult.recommendations.length > 0
                ? validationResult.recommendations.map((r, i) => `${i + 1}. ${r}`).join('\n')
                : '_(No recommendations)_'}

---

## 📋 Next Steps

${validationResult.decision === 'SAFE TO EXECUTE'
                ? '1. ✅ SQL has been validated and is safe to execute\n2. Review the generated SQL above\n3. Execute in the target environment\n4. Monitor execution results'
                : validationResult.decision === 'EXECUTE WITH CAUTION'
                    ? '1. ⚠️ Review the warnings in the validation checklist\n2. Address any concerns before execution\n3. Consider testing in a staging environment first\n4. Execute with appropriate backups in place'
                    : validationResult.decision === 'NEEDS REVIEW'
                        ? '1. 🔍 Manual review required\n2. Check the failed validation items\n3. Consult with database team if needed\n4. Make necessary corrections before execution'
                        : '1. 🚫 DO NOT EXECUTE - SQL has critical issues\n2. Review the failed validation items\n3. Correct the issues in the source file\n4. Re-submit for validation'}

---

*Generated by BEACON (Backend Execution Agent for Case Orchestrated Normalization)*  
*Powered by MOANA SQL Generation + Claude Validation*
`;
    }
}
