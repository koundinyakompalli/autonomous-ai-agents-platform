/**
 * Markdown to ADF (Atlassian Document Format) Converter
 *
 * Converts Markdown text to ADF JSON format for posting to Jira/Confluence.
 * Uses the marklassian library for conversion.
 *
 * Reference:
 * - ADF Spec: https://developer.atlassian.com/cloud/jira/platform/apis/document/structure/
 * - marklassian: https://github.com/ifiokjr/marklassian
 */

import { markdownToAdf } from 'marklassian';
import { createLogger } from './logger.js';

const logger = createLogger('markdown-to-adf');

/**
 * ADF Document node type
 */
export interface AdfDocument {
    version: number;
    type: 'doc';
    content: AdfNode[];
}

/**
 * Generic ADF node
 */
export interface AdfNode {
    type: string;
    attrs?: Record<string, any>;
    content?: AdfNode[];
    text?: string;
    marks?: Array<{ type: string; attrs?: Record<string, any> }>;
}

/**
 * Fix empty block nodes that Jira rejects with INVALID_INPUT.
 *
 * Jira ADF requires tableHeader and tableCell nodes to have at least one
 * child. marklassian produces `content: []` for empty Markdown table headers
 * (e.g. `| | |`), which causes a 400 Bad Request from the Jira comment API.
 */
function fixEmptyTableCells(nodes: AdfNode[]): AdfNode[] {
    return nodes.map(node => {
        if ((node.type === 'tableHeader' || node.type === 'tableCell') &&
            (!node.content || node.content.length === 0)) {
            return { ...node, content: [{ type: 'paragraph', content: [] }] };
        }
        if (node.content && node.content.length > 0) {
            return { ...node, content: fixEmptyTableCells(node.content) };
        }
        return node;
    });
}

/**
 * Convert Markdown to ADF format for Jira/Confluence
 *
 * @param markdown - Markdown text to convert
 * @returns ADF document object
 */
export function convertMarkdownToAdf(markdown: string): AdfDocument {
    try {
        logger.debug( {
            markdownLength: markdown.length,
            preview: markdown.substring(0, 100),
        },'Converting markdown to ADF');

        // Use marklassian to convert
        const adf = markdownToAdf(markdown);

        // Fix empty tableHeader/tableCell nodes — Jira rejects content:[]
        // with INVALID_INPUT. This happens when Markdown tables have empty
        // column headers like `| | |`.
        const fixed = {
            ...adf,
            content: fixEmptyTableCells(adf.content ?? []),
        };

        logger.debug( {
            nodeCount: fixed.content?.length || 0,
            types: fixed.content?.map(n => n.type).join(', '),
        },'Markdown converted to ADF');

        return fixed as AdfDocument;
    } catch (error) {
        logger.error( {
            error: error instanceof Error ? error.message : String(error),
            markdownPreview: markdown.substring(0, 200),
        },'Failed to convert markdown to ADF');

        // Fallback: wrap in code block if conversion fails
        logger.warn('Falling back to code block format');
        return {
            version: 1,
            type: 'doc',
            content: [
                {
                    type: 'codeBlock',
                    attrs: { language: 'markdown' },
                    content: [{ type: 'text', text: markdown }],
                },
            ],
        };
    }
}

/**
 * Create an ADF document with a heading and the converted markdown content
 *
 * @param markdown - Markdown text to convert
 * @param heading - Optional heading to prepend
 * @returns ADF document with heading + converted content
 */
export function convertMarkdownToAdfWithHeading(
    markdown: string,
    heading?: string
): AdfDocument {
    const adf = convertMarkdownToAdf(markdown);

    // If no heading provided, return as-is
    if (!heading) {
        return adf;
    }

    // Prepend heading to content
    const headingNode: AdfNode = {
        type: 'heading',
        attrs: { level: 2 },
        content: [{ type: 'text', text: heading }],
    };

    return {
        version: 1,
        type: 'doc',
        content: [headingNode, ...adf.content],
    };
}

/**
 * Add a footer timestamp to an ADF document
 *
 * @param adf - ADF document to modify
 * @param agentName - Name of the agent that generated the content
 * @returns Modified ADF document with footer
 */
export function addAdfFooter(adf: AdfDocument, agentName?: string): AdfDocument {
    const timestamp = new Date().toISOString();
    const footerText = agentName
        ? `Generated by ${agentName} at ${timestamp}`
        : `Generated at ${timestamp}`;

    const footerNode: AdfNode = {
        type: 'paragraph',
        content: [
            {
                type: 'text',
                text: footerText,
                marks: [{ type: 'em' }],
            },
        ],
    };

    const horizontalRuleNode: AdfNode = {
        type: 'rule',
    };

    return {
        ...adf,
        content: [...adf.content, horizontalRuleNode, footerNode],
    };
}

/**
 * Validate ADF structure
 *
 * @param adf - ADF document to validate
 * @returns true if valid, false otherwise
 */
export function validateAdf(adf: any): adf is AdfDocument {
    if (!adf || typeof adf !== 'object') {
        return false;
    }

    if (adf.type !== 'doc') {
        return false;
    }

    if (adf.version !== 1) {
        return false;
    }

    if (!Array.isArray(adf.content)) {
        return false;
    }

    return true;
}
