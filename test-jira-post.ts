/**
 * Test script to debug JIRA comment posting with file attachments
 * 
 * Run: npx tsx test-jira-post.ts
 */

import { S3Client, GetObjectCommand } from '@aws-sdk/client-s3';
import * as dotenv from 'dotenv';

dotenv.config();

const JIRA_BASE_URL = process.env.JIRA_BASE_URL || 'https://mhkjira.atlassian.net';
const JIRA_USERNAME = process.env.JIRA_USERNAME || 'koundinya.kompalli@mhk.com';
const JIRA_TOKEN = process.env.JIRA_TOKEN!;

// Test data from database
const TEST_TASK = {
    jira_number: 'CPDEV-16546',
    agent_name: 'PRISM',
    result_s3_bucket: 'specter-results',
    result_s3_key: 'results/prism/CPDEV-16546/2-2026-01-26T15-34-47-301Z.md',
};

// JIRA Cloud comment character limit (conservative, actual is ~32767)
const JIRA_COMMENT_LIMIT = 30000;

async function readResultFromS3(bucket: string, key: string): Promise<string> {
    const s3Client = new S3Client({ region: process.env.AWS_REGION || 'us-east-1' });

    console.log(`📥 Reading from S3: ${bucket}/${key}`);

    const command = new GetObjectCommand({ Bucket: bucket, Key: key });
    const response = await s3Client.send(command);

    if (!response.Body) {
        throw new Error('Empty response body from S3');
    }

    const bodyContents = await response.Body.transformToString();
    console.log(`✅ S3 read success - ${bodyContents.length} chars`);
    return bodyContents;
}

async function attachFileToJira(issueKey: string, filename: string, content: string): Promise<void> {
    const auth = Buffer.from(`${JIRA_USERNAME}:${JIRA_TOKEN}`).toString('base64');
    const url = `${JIRA_BASE_URL}/rest/api/3/issue/${issueKey}/attachments`;

    console.log(`\n📎 Attaching file to JIRA ${issueKey}`);
    console.log(`   Filename: ${filename}`);
    console.log(`   Size: ${content.length} chars`);

    // Create multipart form data
    const boundary = '----FormBoundary' + Math.random().toString(36).substring(2);

    const bodyParts = [
        `--${boundary}`,
        `Content-Disposition: form-data; name="file"; filename="${filename}"`,
        'Content-Type: text/markdown',
        '',
        content,
        `--${boundary}--`,
    ];
    const body = bodyParts.join('\r\n');

    const response = await fetch(url, {
        method: 'POST',
        headers: {
            Authorization: `Basic ${auth}`,
            'Content-Type': `multipart/form-data; boundary=${boundary}`,
            'X-Atlassian-Token': 'no-check', // Required for JIRA file uploads
        },
        body,
    });

    console.log(`📬 Response status: ${response.status} ${response.statusText}`);

    if (!response.ok) {
        const errorText = await response.text();
        console.error(`❌ Failed to attach file: ${errorText}`);
        throw new Error(`Failed to attach file: ${response.status} - ${errorText}`);
    }

    const result = await response.json();
    console.log(`✅ File attached successfully!`);
    console.log(`   Attachment details:`, JSON.stringify(result, null, 2).substring(0, 500));
}

async function addJiraComment(issueKey: string, comment: string): Promise<void> {
    const auth = Buffer.from(`${JIRA_USERNAME}:${JIRA_TOKEN}`).toString('base64');
    const url = `${JIRA_BASE_URL}/rest/api/3/issue/${issueKey}/comment`;

    console.log(`\n📤 Posting comment to JIRA ${issueKey}`);
    console.log(`   Comment length: ${comment.length} chars`);

    const formattedComment = {
        body: {
            type: 'doc',
            version: 1,
            content: [
                {
                    type: 'heading',
                    attrs: { level: 2 },
                    content: [{ type: 'text', text: '🤖 Agent Analysis Result' }],
                },
                {
                    type: 'codeBlock',
                    attrs: { language: 'markdown' },
                    content: [{ type: 'text', text: comment }],
                },
                {
                    type: 'paragraph',
                    content: [
                        {
                            type: 'text',
                            text: `Generated by Specter AI Agent at ${new Date().toISOString()}`,
                            marks: [{ type: 'em' }],
                        },
                    ],
                },
            ],
        },
    };

    const response = await fetch(url, {
        method: 'POST',
        headers: {
            Authorization: `Basic ${auth}`,
            'Content-Type': 'application/json',
            Accept: 'application/json',
        },
        body: JSON.stringify(formattedComment),
    });

    console.log(`📬 Response status: ${response.status} ${response.statusText}`);

    if (!response.ok) {
        const errorText = await response.text();
        console.error(`❌ JIRA comment error: ${errorText}`);
        throw new Error(`JIRA API error: ${response.status} - ${errorText}`);
    }

    console.log(`✅ Comment posted successfully!`);
}

function generateSummaryComment(fullResult: string, filename: string): string {
    // Extract a preview from the beginning
    const previewLength = 2000;
    let preview = fullResult.substring(0, previewLength);

    // Try to find a natural break point
    const lastNewlineIndex = preview.lastIndexOf('\n\n');
    if (lastNewlineIndex > previewLength / 2) {
        preview = preview.substring(0, lastNewlineIndex);
    }

    return [
        `## 🤖 ${TEST_TASK.agent_name} Analysis Complete`,
        '',
        `**Full analysis attached as:** \`${filename}\``,
        `**Analysis size:** ${fullResult.length.toLocaleString()} characters`,
        '',
        '---',
        '',
        '### Preview',
        '',
        preview,
        '',
        '...',
        '',
        `*See attached file \`${filename}\` for full analysis*`,
    ].join('\n');
}

async function testGetIssue(issueKey: string): Promise<void> {
    const auth = Buffer.from(`${JIRA_USERNAME}:${JIRA_TOKEN}`).toString('base64');
    const url = `${JIRA_BASE_URL}/rest/api/3/issue/${issueKey}`;

    console.log(`\n🔍 Testing GET issue ${issueKey}`);

    const response = await fetch(url, {
        method: 'GET',
        headers: {
            Authorization: `Basic ${auth}`,
            Accept: 'application/json',
        },
    });

    console.log(`📬 Response status: ${response.status} ${response.statusText}`);

    if (response.ok) {
        const data = await response.json();
        console.log(`✅ Got issue: ${data.key} - ${data.fields?.summary}`);
    } else {
        const text = await response.text();
        console.error(`❌ Failed: ${text}`);
    }
}

async function main() {
    console.log('========================================');
    console.log('JIRA Post Test (with Attachments)');
    console.log('========================================');
    console.log(`JIRA_BASE_URL: ${JIRA_BASE_URL}`);
    console.log(`JIRA_USERNAME: ${JIRA_USERNAME}`);
    console.log(`JIRA_TOKEN: ${JIRA_TOKEN ? 'SET (' + JIRA_TOKEN.length + ' chars)' : 'NOT SET'}`);
    console.log(`Issue: ${TEST_TASK.jira_number}`);
    console.log(`Comment Limit: ${JIRA_COMMENT_LIMIT} chars`);
    console.log('========================================\n');

    // Step 1: Test GET issue (verify auth works)
    await testGetIssue(TEST_TASK.jira_number);

    // Step 2: Read result from S3
    let fullResult: string;
    try {
        fullResult = await readResultFromS3(TEST_TASK.result_s3_bucket, TEST_TASK.result_s3_key);
        console.log(`\n📄 Result size: ${fullResult.length} chars (limit: ${JIRA_COMMENT_LIMIT})`);
        console.log(`📄 Preview:\n${fullResult.substring(0, 500)}...\n`);
    } catch (error) {
        console.error('❌ Failed to read from S3:', error);
        fullResult = '## Test Comment\n\nThis is a test comment from Specter.';
    }

    // Step 3: Handle based on size
    if (fullResult.length > JIRA_COMMENT_LIMIT) {
        console.log(`\n⚠️ Result exceeds JIRA limit - will attach as file`);

        // Generate filename
        const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
        const filename = `${TEST_TASK.agent_name}_analysis_${timestamp}.md`;

        // Attach the full result as a file
        await attachFileToJira(TEST_TASK.jira_number, filename, fullResult);

        // Post a summary comment
        const summaryComment = generateSummaryComment(fullResult, filename);
        console.log(`\n📝 Summary comment (${summaryComment.length} chars):`);
        console.log(summaryComment.substring(0, 500) + '...\n');

        await addJiraComment(TEST_TASK.jira_number, summaryComment);
    } else {
        // Post full result as comment
        await addJiraComment(TEST_TASK.jira_number, fullResult);
    }

    console.log('\n✅ All done!');
}

main().catch(console.error);
