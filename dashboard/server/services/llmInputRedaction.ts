/**
 * Strict allowlist redactor for the OneShot Statistics LLM prompt.
 *
 * The prompt is the only outbound path that ships ticket-derived text to a
 * third-party model (Bedrock). To eliminate any chance of PHI/free-text
 * leakage, the redactor reduces every shape we send to:
 *   - Jira keys
 *   - bucket / category / signal labels (controlled vocabulary)
 *   - numeric metrics, sample sizes, pass rates, Wilson bounds
 *
 * Anything else (titles, error summaries, free-text reasons) is dropped
 * before the JSON.stringify at oneshotStatistics.ts:~1581.
 *
 * The LLM can still reference tickets by Jira key — operators click through
 * to the dashboard to read titles themselves.
 */

import type {
  OneShotFailureAttributionSummary,
  OneShotMissingSignalImpact,
  OneShotOperationalBottleneckSummary,
  OneShotRepoStatusSummary,
  OneShotStatisticsBucket,
  OneShotStatisticsJiraExample,
  OneShotStatisticsScorecard,
  OneShotTicketQualityAnalysis,
} from "../types/oneshot.js";

export interface RedactedJiraExample {
  jiraKey: string;
}

export interface RedactedBucket {
  id: string;
  label: string;
  kind: string;
  sampleSize: number;
  completed: number;
  failed: number;
  noAction: number;
  passRate: number;
  examples: RedactedJiraExample[];
}

export interface RedactedFailureAttribution {
  totalFailures: number;
  excludedFromDenominator: number;
  countsByAttribution: OneShotFailureAttributionSummary["countsByAttribution"];
  byCategory: Array<{
    errorCategory: string;
    attribution: string;
    sampleSize: number;
    significant: boolean;
    examples: RedactedJiraExample[];
  }>;
  attributionVersion: number;
}

export interface RedactedMissingSignalImpact {
  signal: OneShotMissingSignalImpact["signal"];
  label: string;
  signals?: readonly string[];
  missing: OneShotMissingSignalImpact["missing"];
  present: OneShotMissingSignalImpact["present"];
  deltaPassRate: number;
  significant: boolean;
  examples: {
    missingFailedOrNoAction: RedactedJiraExample[];
    presentPassed: RedactedJiraExample[];
  };
}

export interface RedactedTicketQuality {
  rubric: OneShotTicketQualityAnalysis["rubric"];
  totalIntake: number;
  averageScore: number;
  readinessDistribution: ReadonlyArray<{
    id: string;
    label: string;
    sampleSize: number;
    share: number;
    cohort: OneShotTicketQualityAnalysis["readinessDistribution"][number]["cohort"];
    averageScore: number;
  }>;
  passRateByTier: ReadonlyArray<{
    id: string;
    label: string;
    sampleSize: number;
    cohort: OneShotTicketQualityAnalysis["passRateByTier"][number]["cohort"];
  }>;
  templateFit: ReadonlyArray<{
    id: string;
    label: string;
    sampleSize: number;
    share: number;
    cohort: OneShotTicketQualityAnalysis["templateFit"][number]["cohort"];
    averageScore: number;
  }>;
  missingSignalImpact: RedactedMissingSignalImpact[];
  /**
   * dataHygieneCallout's title and summary are controlled-vocabulary strings
   * generated by the deterministic builder, but examples carry ticket titles
   * — strip those down to keys.
   */
  dataHygieneCallout:
    | (Omit<
        NonNullable<OneShotTicketQualityAnalysis["dataHygieneCallout"]>,
        "examples"
      > & {
        examples: RedactedJiraExample[];
      })
    | null;
  stratifiedReadinessGap: OneShotTicketQualityAnalysis["stratifiedReadinessGap"];
}

export interface RedactedRepoStatus {
  range: OneShotRepoStatusSummary["range"];
  statusVersion: number;
  rows: Array<{
    repoKey: string;
    repoLabel: string;
    status: string;
    isUnresolved: boolean;
    sampleSize: number;
    terminalCount: number;
    completed: number;
    failed: number;
    noAction: number;
    passRate: number;
    wilson95: OneShotRepoStatusSummary["rows"][number]["wilson95"];
    topStageIssue: OneShotRepoStatusSummary["rows"][number]["topStageIssue"];
    topFailureAttribution: OneShotRepoStatusSummary["rows"][number]["topFailureAttribution"];
    examples: RedactedJiraExample[];
  }>;
}

export interface RedactedOperationalBottlenecks {
  range: OneShotOperationalBottleneckSummary["range"];
  bottleneckVersion: number;
  rows: Array<{
    id: string;
    kind: string;
    severity: string;
    title: string;
    nextStep: string;
    affected: number;
    failed: number;
    noAction: number;
    passRate: number;
    repoKey: string | null;
    repoLabel: string | null;
    stage: OneShotOperationalBottleneckSummary["rows"][number]["stage"];
    stageLabel: string | null;
    failureAttribution: OneShotOperationalBottleneckSummary["rows"][number]["failureAttribution"];
    costUsd: number;
    tokens: number;
    examples: RedactedJiraExample[];
  }>;
}

export function redactJiraExampleForLlm(
  example: OneShotStatisticsJiraExample,
): RedactedJiraExample {
  return { jiraKey: example.jiraKey };
}

export function redactBucketForLlm(
  bucket: OneShotStatisticsBucket,
): RedactedBucket {
  return {
    id: bucket.id,
    label: bucket.label,
    kind: bucket.kind,
    sampleSize: bucket.sampleSize,
    completed: bucket.completed,
    failed: bucket.failed,
    noAction: bucket.noAction,
    passRate: bucket.passRate,
    examples: bucket.examples.map(redactJiraExampleForLlm),
  };
}

export function redactFailureAttributionForLlm(
  summary: OneShotFailureAttributionSummary,
): RedactedFailureAttribution {
  return {
    totalFailures: summary.totalFailures,
    excludedFromDenominator: summary.excludedFromDenominator,
    countsByAttribution: summary.countsByAttribution,
    byCategory: summary.byCategory.map((row) => ({
      errorCategory: row.errorCategory,
      attribution: row.attribution,
      sampleSize: row.sampleSize,
      significant: row.significant,
      examples: row.examples.map(redactJiraExampleForLlm),
    })),
    attributionVersion: summary.attributionVersion,
  };
}

export function redactMissingSignalImpactForLlm(
  impact: OneShotMissingSignalImpact,
): RedactedMissingSignalImpact {
  return {
    signal: impact.signal,
    label: impact.label,
    signals: impact.signals,
    missing: impact.missing,
    present: impact.present,
    deltaPassRate: impact.deltaPassRate,
    significant: impact.significant,
    examples: {
      missingFailedOrNoAction: impact.examples.missingFailedOrNoAction.map(
        redactJiraExampleForLlm,
      ),
      presentPassed: impact.examples.presentPassed.map(redactJiraExampleForLlm),
    },
  };
}

export function redactTicketQualityForLlm(
  ticketQuality: OneShotTicketQualityAnalysis,
): RedactedTicketQuality {
  return {
    rubric: ticketQuality.rubric,
    totalIntake: ticketQuality.totalIntake,
    averageScore: ticketQuality.averageScore,
    readinessDistribution: ticketQuality.readinessDistribution.map((b) => ({
      id: b.id,
      label: b.label,
      sampleSize: b.sampleSize,
      share: b.share,
      cohort: b.cohort,
      averageScore: b.averageScore,
    })),
    passRateByTier: ticketQuality.passRateByTier.map((b) => ({
      id: b.id,
      label: b.label,
      sampleSize: b.sampleSize,
      cohort: b.cohort,
    })),
    templateFit: ticketQuality.templateFit.map((b) => ({
      id: b.id,
      label: b.label,
      sampleSize: b.sampleSize,
      share: b.share,
      cohort: b.cohort,
      averageScore: b.averageScore,
    })),
    missingSignalImpact: ticketQuality.missingSignalImpact.map(
      redactMissingSignalImpactForLlm,
    ),
    dataHygieneCallout: ticketQuality.dataHygieneCallout
      ? {
          ...ticketQuality.dataHygieneCallout,
          examples: ticketQuality.dataHygieneCallout.examples.map(
            redactJiraExampleForLlm,
          ),
        }
      : null,
    stratifiedReadinessGap: ticketQuality.stratifiedReadinessGap,
  };
}

